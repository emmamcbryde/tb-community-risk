"""Isolated scientific gate and grid-audited diagnostic inversion. Offline only.

Nothing in this module changes the public baseline-TBI source dispatcher.
Review receipts are declarations by a reviewer, not evidence generated by a hash.
Synthetic receipts cannot authorize an empirical population.
"""
from copy import deepcopy
from math import isfinite

from engine.country_tb.data_common import canonical, profile_hash, seal, DataValidationError
from engine.country_tb.composition_common import require
from engine.country_tb.progression_common import number

VERSION = 'country_tb_incidence_diagnostic_1.0.0'
OBSERVATION = 'country_tb.active_tb_incidence_observation.v1'
GATE = 'country_tb.incidence_inversion_gate.v1'
CALIBRATION = 'country_tb.incidence_to_tbi_diagnostic_calibration.v1'
IDENTIFIABILITY = 'country_tb.incidence_identifiability_report.v1'
EVIDENCE = 'country_tb.progression_evidence_review.v1'
RECONCILIATION = 'country_tb.incidence_reconciliation_report.v1'
PUBLIC_STATUS = 'unavailable_pending_progression_and_risk_forward_operator'


def artifact(family, **fields):
    return seal(dict(schema_id=family, contract_version='1.0.0', implementation_version=VERSION,
        production_available=False, purpose='planning_and_sequencing_not_denying_care', **deepcopy(fields)))


def verify(value, family):
    require(isinstance(value, dict) and value.get('schema_id') == family and
        value.get('implementation_version') == VERSION and value.get('contract_version') == '1.0.0',
        'Unknown diagnostic contract/version.')
    require(value.get('profile_hash') == profile_hash(value), 'Diagnostic scientific hash mismatch.')
    require(value.get('production_available') is False, 'Production incidence inference is not approved.')
    return value


def provenance(source, review, history):
    require(isinstance(source, dict) and bool(source.get('source_id')), 'Source identifier required.')
    require(isinstance(review, dict) and review.get('status') in {'reviewed','pending','rejected'}, 'Review status required.')
    require(isinstance(history, dict) and bool(history), 'Nonempty provenance required.')


def incidence_observation(*, geography_id, geography_level, subgroup_id, year, target_type,
    rate_per_100000_person_years, count, denominator_person_years, observation_period_years, measure,
    age_lower, age_upper_exclusive, sex, uncertainty, incident_or_prevalent, episode,
    acquisition, resident_compatibility, ascertainment, source, review, provenance_record,
    adjustments=None):
    """No notification-to-incidence or recurrent-to-first-episode default adjustment."""
    provenance(source, review, provenance_record)
    require(measure in {'instantaneous_baseline_per_100000_person_years','prospective_per_100000_person_years'}, 'Explicit incidence observation measure required.')
    require(geography_id and subgroup_id and geography_level in {'national','subnational','custom'}, 'Population identity required.')
    require(type(year) is int and type(age_lower) is int and age_lower >= 0 and
        (age_upper_exclusive is None or type(age_upper_exclusive) is int and age_upper_exclusive > age_lower), 'Invalid observation ages/year.')
    require(sex in {'both','female','male'}, 'Explicit observation sex required.')
    require(target_type in {'incident_disease','notifications','baseline_prevalent_disease',
        'screen_detected_prevalent_disease','imported_active_disease','mixed_or_unclear'}, 'Unknown active-TB observation type.')
    require(incident_or_prevalent in {'incident','prevalent','unknown'} and episode in
        {'first','new_and_recurrent','recurrent','unknown'}, 'Episode/incidence semantics required.')
    require(acquisition in {'represented_exposure_history','imported','mixed','unknown'} and
        resident_compatibility in {'compatible','incompatible','unknown'}, 'Acquisition/residence semantics required.')
    require(isinstance(ascertainment, dict) and ascertainment.get('status') in {'reviewed','unknown','incompatible'}, 'Ascertainment status required.')
    require(number(observation_period_years) > 0, 'Observation period must be positive.')
    require(denominator_person_years is not None and number(denominator_person_years) > 0, 'Positive person-time denominator required; a population count alone is not person-time.')
    require(rate_per_100000_person_years is not None or count is not None, 'Rate or count required.')
    rate = number(rate_per_100000_person_years) if rate_per_100000_person_years is not None else 100000*number(count)/number(denominator_person_years)
    require(rate >= 0 and (count is None or number(count) >= 0), 'Negative incidence/count.')
    if count is not None:
        require(abs(100000*number(count)/number(denominator_person_years)-rate) <= 1e-8*max(1., rate), 'Rate/count/person-time inconsistency; no clipping.')
    if uncertainty is not None:
        require(set(uncertainty) >= {'lower','upper','kind'} and 0 <= number(uncertainty['lower']) <= rate <= number(uncertainty['upper']), 'Invalid target uncertainty.')
    adjusted = deepcopy(adjustments)
    native = (target_type == 'incident_disease' and incident_or_prevalent == 'incident' and episode == 'first'
        and acquisition == 'represented_exposure_history' and resident_compatibility == 'compatible')
    compatibility = 'compatible' if native else 'validation_only'
    if resident_compatibility == 'incompatible' or target_type in {'baseline_prevalent_disease','screen_detected_prevalent_disease','imported_active_disease'}:
        compatibility = 'incompatible'
    if target_type == 'mixed_or_unclear' or incident_or_prevalent == 'unknown': compatibility = 'insufficiently_specified'
    if review['status'] != 'reviewed' or ascertainment['status'] != 'reviewed': compatibility = 'insufficiently_specified'
    if adjusted is not None:
        require(isinstance(adjusted, dict) and set(adjusted) >= {'observation_model','adjusted_rate','source','review','provenance','resolves'}, 'Complete reviewed adjustment contract required.')
        provenance(adjusted['source'], adjusted['review'], adjusted['provenance'])
        require(adjusted['review']['status'] == 'reviewed' and adjusted['observation_model'], 'Adjustment must be reviewed.')
        required = {'incident_first_episode','represented_exposure_history','resident_population','ascertainment'}
        require(set(adjusted['resolves']) == required, 'Adjustment must explicitly resolve all observation mismatches.')
        require(number(adjusted['adjusted_rate']) >= 0, 'Negative adjusted target.')
        # Prevalence and imported-only observations are never incidence merely by relabelling.
        require(target_type in {'incident_disease','notifications','mixed_or_unclear'} and incident_or_prevalent != 'prevalent', 'This target requires a separate incidence observation, not a prevalence conversion.')
        require(review['status'] == 'reviewed' and ascertainment['status'] == 'reviewed', 'Original target/ascertainment also require review.')
        compatibility = 'compatible_after_reviewed_adjustment'
    return artifact(OBSERVATION, geography_id=geography_id, geography_level=geography_level,
        subgroup_id=subgroup_id, year=year, target_type=target_type, rate_per_100000_person_years=rate,
        count=count, denominator_person_years=denominator_person_years, observation_period_years=observation_period_years,
        measure=measure,
        age_lower=age_lower, age_upper_exclusive=age_upper_exclusive, sex=sex, uncertainty=uncertainty,
        incident_or_prevalent=incident_or_prevalent, episode=episode, acquisition=acquisition,
        resident_compatibility=resident_compatibility, ascertainment=ascertainment, compatibility=compatibility,
        adjustments=adjusted, calibration_target=number(adjusted['adjusted_rate']) if adjusted else rate,
        source=source, review=review, provenance=provenance_record)


def inversion_gate(mapping, observation, *, unresolved_threshold_approval, scientific_review,
    concentration_policy, source, review, provenance_record):
    """All approvals bind to the exact scenario hash and observation population.

    Threshold approval is mandatory; None records pending, never a default.
    A protocol_scope='synthetic_test_only' receipt only authorizes a fictional case.
    """
    verify(observation, OBSERVATION); provenance(source, review, provenance_record)
    s = mapping.specification
    require(s['profile_hash']==profile_hash(s) and s['operator_hash']==mapping.operator['profile_hash'] and
        s['history_hash']==mapping.history['profile_hash'], 'Mapping scientific inputs changed after compilation.')
    require(isinstance(scientific_review, dict), 'Explicit scientific review receipt required.')
    checks = {}
    checks['observation_compatible'] = observation['compatibility'] in {'compatible','compatible_after_reviewed_adjustment'}
    checks['same_observation_population'] = (observation['geography_id'] == s['geography_id'] and observation['subgroup_id'] == s['subgroup_id']
        and observation['year'] == s['baseline_year'] and observation['sex'] == s['sex_scope'] and
        observation['age_lower'] == s['age_lower'] and observation['age_upper_exclusive'] == s['age_upper_exclusive'] and
        observation['measure'] == s['measure'] and
        (s['measure'].startswith('instantaneous') or number(observation['observation_period_years'])==s['horizon_years']))
    checks['review_binds_scenario'] = scientific_review.get('scenario_hash') == s['profile_hash'] and scientific_review.get('status') == 'reviewed'
    checks['review_provenance'] = bool(scientific_review.get('source_id')) and bool(scientific_review.get('provenance'))
    scope = scientific_review.get('protocol_scope')
    checks['review_scope'] = scope == 'reviewed_empirical_configuration' or scope == 'synthetic_test_only' and s['population_kind'] == 'synthetic_closed_population'
    for field in ('progression_curves','remote_tail','risk_effect_application','mortality','migration_importation_recurrence','prior_tb_and_depletion','future_pressure'):
        checks[field+'_reviewed'] = scientific_review.get(field) == 'reviewed'
    # Synthetic curve status is allowed only for explicitly fictional mathematical validation.
    curves = [c for cs in [mapping.operator['natural_history']['group_curves'], *mapping.operator['natural_history']['sex_curves'].values()] for c in cs.values() if c]
    checks['curve_evidence_status'] = scope == 'synthetic_test_only' and s['population_kind'] == 'synthetic_closed_population' or all(c['status'] == 'reviewed_external' for c in curves)
    checks['all_material_age_curves'] = not mapping.material_curve_gaps
    checks['explicit_remote_tail'] = not mapping.tail_gaps
    checks['mortality_explicit'] = mapping.operator['competing_mortality']['mode'] != 'no_mortality_diagnostic_v1' or scope == 'synthetic_test_only' and s['population_kind'] == 'synthetic_closed_population'
    mortality=mapping.operator['competing_mortality']
    import re
    checks['mortality_snapshot_reviewed'] = (scope=='synthetic_test_only' and s['population_kind']=='synthetic_closed_population' or
        isinstance(mortality.get('snapshot_hash'),str) and bool(re.fullmatch('[0-9a-f]{64}',mortality['snapshot_hash']))
        and isinstance(mortality.get('licensing'),dict) and mortality['licensing'].get('status')=='reviewed')
    checks['migration_metadata_addressed'] = all(s['population_history'].get(k) is not None for k in
        ('exposure_geography','arrival_year_policy','imported_active_contribution','prior_tb_prevalence','recurrence_contribution','historical_depletion_policy'))
    approval = deepcopy(unresolved_threshold_approval)
    if approval is not None:
        require(set(approval) >= {'maximum_share','approved_by','source_id','provenance','scope'}, 'Threshold approval needs approver and provenance.')
        require(0 <= number(approval['maximum_share']) < 1 and approval['approved_by'] and approval['source_id'] and approval['provenance'], 'Invalid threshold approval.')
        require(approval['scope'] in {'synthetic_test_only','diagnostic_configuration'}, 'Unknown threshold approval scope.')
    checks['threshold_approved'] = approval is not None and (approval['scope'] != 'synthetic_test_only' or s['population_kind'] == 'synthetic_closed_population')
    # Conservative whole-cell unresolved share across the entire declared search, not alpha=0 only.
    checks['unresolved_population'] = checks['threshold_approved'] and mapping.maximum_unresolved_share <= number(approval['maximum_share'])
    # A tolerance ceiling does not supply missing hazards or an observation
    # model for an uncovered denominator. This solver fits defined complete
    # predictions only; otherwise return a structured gate refusal, not a
    # root-finder exception or a covered-only country rate.
    checks['forward_prediction_defined_for_target'] = mapping.maximum_unresolved_share==0 and not mapping.tail_gaps
    require(isinstance(concentration_policy, dict) and set(concentration_policy) >= {'top_population_share','maximum_case_share','source_id','review'}, 'Explicit concentration warning threshold required.')
    require(0 < number(concentration_policy['top_population_share']) <= 1 and 0 < number(concentration_policy['maximum_case_share']) <= 1, 'Invalid concentration threshold.')
    checks['risk_effects_reviewed'] = not mapping.unreviewed_risk_factors
    checks['review_record_approved'] = review['status'] == 'reviewed'
    return artifact(GATE, scenario_hash=s['profile_hash'], observation_hash=observation['profile_hash'],
        checks=checks, failed_criteria=sorted(k for k,v in checks.items() if not v),
        prefit_allowed=all(checks.values()), unresolved_threshold_approval=approval,
        threshold_candidates=[{'maximum_share':v,'meaning':m} for v,m in [(0,'complete coverage'),(.001,'0.1% explicitly unresolved'),(.01,'1% explicitly unresolved')]],
        maximum_unresolved_share=mapping.maximum_unresolved_share, concentration_policy=concentration_policy,
        scientific_review=scientific_review, postfit_requirements=['identifiable_mapping','target_attainable','numerical_convergence','concentration'],
        public_status=PUBLIC_STATUS, source=source, review=review, provenance=provenance_record)


def _bisect(function, lo, hi, *, xtol, ytol, iterations=100):
    a,b = function(lo),function(hi)
    if abs(a) <= ytol: return lo
    if abs(b) <= ytol: return hi
    require(a*b < 0, 'Root is not bracketed.')
    for _ in range(iterations):
        mid=(lo+hi)/2; f=function(mid)
        if abs(f) <= ytol and hi-lo <= xtol*max(1., abs(mid)): return mid
        if a*f <= 0: hi,b=mid,f
        else: lo,a=mid,f
    return (lo+hi)/2


def assess_identifiability(function, *, lower, upper, target, grid_intervals=256,
    incidence_tolerance=1e-7, alpha_tolerance=1e-10, flat_slope_tolerance=1e-7,
    scenario_hash, source, review, provenance_record):
    """Grid + independent half-grid + finite-difference stationary-point audit.

    Reports grid-resolved identifiability, never an analytical global theorem.
    Tangencies at stationary points are included in all-root search.
    """
    provenance(source, review, provenance_record)
    lo,hi,t = number(lower),number(upper),number(target)
    require(0 <= lo < hi and t >= 0, 'Invalid non-negative search interval/target.')
    require(type(grid_intervals) is int and 32 <= grid_intervals <= 4096, 'Bounded dense grid of 32--4096 intervals required.')
    require(incidence_tolerance > 0 and alpha_tolerance > 0 and flat_slope_tolerance > 0, 'Explicit positive numerical tolerances required.')
    cache={}
    def f(x):
        if x not in cache:
            y=function(x); require(y is not None and isfinite(y) and y >= 0, 'Unresolved/nonfinite/negative forward result cannot enter root finding.')
            cache[x]=float(y)
        return cache[x]
    # Linear plus logarithmic spacing resolves small-alpha transitions and the full bracket.
    xs={lo,hi}
    from math import exp,log
    for n in (grid_intervals,2*grid_intervals):
        xs.update(lo+(hi-lo)*i/n for i in range(n+1))
    for i in range(2*grid_intervals+1):
        xs.add(lo+(hi-lo)*exp(log(1e-8)*(1-i/(2*grid_intervals))))
    xs=sorted(xs)
    ys=[f(x) for x in xs]
    def derivative(x, factor=1.):
        delta=max(1e-9, (hi-lo)*1e-5)*factor
        a=max(lo,x-delta);b=min(hi,x+delta)
        return (f(b)-f(a))/(b-a)
    extrema=[]
    for i in range(1,len(xs)-1):
        left=ys[i]-ys[i-1];right=ys[i+1]-ys[i]
        if left*right < 0:
            a,b=xs[i-1],xs[i+1]
            da,db=derivative(a),derivative(b)
            if da*db < 0:
                point=_bisect(derivative,a,b,xtol=alpha_tolerance,ytol=flat_slope_tolerance)
                extrema.append(point)
    xs=sorted(set(xs+extrema));ys=[f(x) for x in xs]
    slopes=[(b-a)/(v-u) for u,v,a,b in zip(xs,xs[1:],ys,ys[1:])]
    growing=any(v>flat_slope_tolerance for v in slopes);falling=any(v < -flat_slope_tolerance for v in slopes)
    flat=max(ys)-min(ys) <= incidence_tolerance
    nonmonotonic=growing and falling
    roots=[]
    def add(x):
        if not any(abs(x-r) <= alpha_tolerance*10*max(1., abs(x)) for r in roots):roots.append(x)
    if not flat:
        # Do not turn every near-equal saturated grid point into a root.
        for x,y in zip(xs,ys):
            if abs(y-t) <= incidence_tolerance and (x in (lo,hi) or x in extrema): add(x)
        for a,b,ya,yb in zip(xs,xs[1:],ys,ys[1:]):
            if (ya-t)*(yb-t)<0:add(_bisect(lambda x:f(x)-t,a,b,xtol=alpha_tolerance,ytol=incidence_tolerance))
    roots=sorted(roots)
    flat_at_roots=any(abs(derivative(x))<=flat_slope_tolerance for x in roots)
    attainable=min(ys)-incidence_tolerance <= t <= max(ys)+incidence_tolerance
    converged=bool(roots) and all(abs(f(x)-t)<=incidence_tolerance for x in roots)
    unique=not flat and not nonmonotonic and len(roots)==1 and not flat_at_roots and converged
    flat_regions=[]
    for a,b,slope in zip(xs,xs[1:],slopes):
        if abs(slope)<=flat_slope_tolerance:
            if flat_regions and flat_regions[-1][1]==a:flat_regions[-1][1]=b
            else:flat_regions.append([a,b])
    diagnostics=[]
    for x in roots:
        d=derivative(x);d2=derivative(x,.5)
        diagnostics.append({'alpha':x,'predicted_incidence':f(x),'derivative_incidence_per_alpha':d,
            'derivative_half_step':d2,'derivative_refinement_difference':abs(d-d2),
            'inverse_sensitivity_alpha_per_incidence':None if d==0 else 1/d,
            'relative_condition_alpha':None if x==0 or d==0 else abs(t/(x*d)),
            'boundary':x==lo or x==hi,'numerical_residual':f(x)-t})
    coarse=[lo+(hi-lo)*i/grid_intervals for i in range(grid_intervals+1)]
    refined=[lo+(hi-lo)*i/(2*grid_intervals) for i in range(2*grid_intervals+1)]
    def crossings(grid):return sum((f(a)-t)*(f(b)-t)<0 for a,b in zip(grid,grid[1:]))
    return artifact(IDENTIFIABILITY,scenario_hash=scenario_hash,search_interval=[lo,hi],target=t,
        grid_intervals=grid_intervals,grid_rows=[{'alpha':x,'incidence':y} for x,y in zip(xs,ys)],
        continuity='numerical_grid_audit_not_an_analytic_proof',monotonicity='flat' if flat else 'non_monotonic' if nonmonotonic else 'increasing' if growing else 'decreasing',
        attainable_range=[min(ys),max(ys)],target_attainable=attainable,stationary_points=sorted(extrema),
        flat_regions=flat_regions,saturation_warning=bool(flat_regions),
        all_roots=diagnostics,identifiable_over_search_interval=unique,
        numerical_convergence=converged,
        failure_status='flat_or_saturated_mapping' if flat or flat_at_roots else 'non_monotonic_mapping' if nonmonotonic else 'target_outside_attainable_range' if not attainable else 'no_resolved_root' if not roots else 'multiple_roots' if len(roots)>1 else 'numerical_nonconvergence' if not converged else None,
        grid_refinement={'coarse_crossings':crossings(coarse),'refined_crossings':crossings(refined),
            'coarse_range':[min(map(f,coarse)),max(map(f,coarse))],'refined_range':[min(map(f,refined)),max(map(f,refined))]},
        tolerances={'incidence':incidence_tolerance,'alpha':alpha_tolerance,'flat_slope':flat_slope_tolerance},
        source=source,review=review,provenance=provenance_record)


def diagnostic_calibration(mapping, observation, gate, *, lower, upper, grid_intervals=256,
    source, review, provenance_record):
    verify(observation,OBSERVATION);verify(gate,GATE);provenance(source,review,provenance_record)
    require(gate['scenario_hash']==mapping.specification['profile_hash'] and gate['observation_hash']==observation['profile_hash'], 'Gate belongs to a different configuration/target.')
    rebuilt=inversion_gate(mapping,observation,unresolved_threshold_approval=gate['unresolved_threshold_approval'],
        scientific_review=gate['scientific_review'],concentration_policy=gate['concentration_policy'],
        source=gate['source'],review=gate['review'],provenance_record=gate['provenance'])
    require(canonical(rebuilt)==canonical(gate),'Gate checks must reproduce; status flags alone cannot approve inversion.')
    base=dict(scenario_hash=mapping.specification['profile_hash'],observation=observation,gate=gate,
        public_status=PUBLIC_STATUS,source=source,review=review,provenance=provenance_record)
    if not gate['prefit_allowed']:
        return artifact(CALIBRATION,status='blocked_scientific_gate',fitted_scale=None,profile=None,
            achieved_incidence=None,identifiability=None,failures=gate['failed_criteria'],**base)
    report=assess_identifiability(mapping.incidence,lower=lower,upper=upper,
        target=observation['calibration_target'],grid_intervals=grid_intervals,
        scenario_hash=mapping.specification['profile_hash'],source=source,review=review,provenance_record=provenance_record)
    if not report['identifiable_over_search_interval']:
        return artifact(CALIBRATION,status='rejected_nonidentifiable_or_infeasible',fitted_scale=None,
            profile=None,achieved_incidence=None,identifiability=report,failures=[report['failure_status']],**base)
    root=report['all_roots'][0]['alpha'];value=mapping.evaluate(root)
    try:
        fine_mapping=mapping.refined();fine=fine_mapping.evaluate(root)
        require(fine['incidence'] is not None,'refined_forward_kernel_unresolved')
    except DataValidationError as exc:
        return artifact(CALIBRATION,status='blocked_postfit_gate',fitted_scale=None,profile=None,
            achieved_incidence=None,identifiability=report,failures=[str(exc)],**base)
    delta=abs(fine['incidence']-value['incidence'])
    threshold=1e-5*max(1.,value['incidence'])
    cp=gate['concentration_policy'];concentration=mapping.concentration(root,number(cp['top_population_share']))
    dominated=bool(mapping.unreviewed_risk_factors) and concentration['case_share'] is not None and concentration['case_share']>number(cp['maximum_case_share'])
    # Independent narrower bracket around root, with root at neither artificial endpoint.
    width=(number(upper)-number(lower))/10
    a=max(number(lower),root-width);b=min(number(upper),root+width)
    refined_report=assess_identifiability(mapping.incidence,lower=a,upper=b,
        target=observation['calibration_target'],grid_intervals=max(32,grid_intervals//2),
        scenario_hash=mapping.specification['profile_hash'],source=source,review=review,provenance_record=provenance_record)
    stable=bool(refined_report['all_roots']) and abs(refined_report['all_roots'][0]['alpha']-root)<1e-8
    passed=delta<=threshold and stable and not dominated
    epsilon=max(1e-9,(number(upper)-number(lower))*1e-5)
    aa=max(number(lower),root-epsilon);bb=min(number(upper),root+epsilon)
    p=mapping.total_tbi(root);pa=mapping.total_tbi(aa);pb=mapping.total_tbi(bb)
    dI=report['all_roots'][0]['derivative_incidence_per_alpha']
    condition_tbi=None if p is None or p==0 or dI==0 else abs(observation['calibration_target']*(pb-pa)/(bb-aa)/(p*dI))
    # Inferred conditional profile is adopted only if every scientific/numerical gate passed.
    return artifact(CALIBRATION,status='diagnostic_only_not_approved_for_production' if passed else 'blocked_postfit_gate',
        fitted_scale=root if passed else None,profile=value if passed else None,achieved_incidence=value['incidence'] if passed else None,
        identifiability=report,numerical_checks={'integration_refinement_difference':delta,'allowed_difference':threshold,
            'bracket_invariant':stable,'refined_bracket_hash':refined_report['profile_hash'],
            'refined_scenario_hash':fine_mapping.specification['profile_hash'],
            'refinement':'half_response_width_and_half_future_time_step_when_exogenous'},concentration=concentration,
        relative_condition_total_tbi=condition_tbi,
        failures=[] if passed else ['integration_or_bracket_or_concentration_gate'],**base)


def reconcile_incidence(profile, observation, *, source, review, provenance_record):
    """Validation only: preserves the supplied profile byte-for-byte in this artifact."""
    verify(observation,OBSERVATION);provenance(source,review,provenance_record)
    before=canonical(profile);pred=profile.get('incidence');target=observation['rate_per_100000_person_years']
    value=artifact(RECONCILIATION,status='validation_only_not_calibration',supplied_profile=profile,
        supplied_profile_hash=profile_hash(profile),observation=observation,predicted_incidence=pred,
        target_incidence=target,difference=None if pred is None else pred-target,
        ratio=None if pred is None or target==0 else pred/target,
        measure_compatibility='matched' if profile.get('measure')==observation['measure'] else 'validation_only_measure_or_period_mismatch',
        compatibility_warning=observation['compatibility'],unresolved_population=profile.get('unresolved_population'),
        exclusions=['recurrence','imported_active_disease','migration','historical_TB_depletion','endogenous_transmission'],
        public_status=PUBLIC_STATUS,source=source,review=review,provenance=provenance_record)
    require(before==canonical(profile),'Validation mutated user TBI.')
    return value
