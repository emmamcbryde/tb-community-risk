function uiState = economics_config_to_ui_state_v9(econConfig)
%ECONOMICS_CONFIG_TO_UI_STATE_V9 Convert economics config to flat UI state.

if nargin < 1 || isempty(econConfig)
    econConfig = build_default_economics_config_v9();
end

uiState = struct();
uiState.fieldValues = struct();

fields = economics_ui_field_map_v9();
for i = 1:numel(fields)
    uiState.fieldValues.(fields(i).componentName) = get_nested_field(econConfig, fields(i).configPath);
end
end

