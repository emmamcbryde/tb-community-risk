end

function value = get_nested_field(s, path)
value = [];
parts = strsplit(path, '.');
value = s;
for i = 1:numel(parts)
    if ~isstruct(value) || ~isfield(value, parts{i})
        value = [];
        return;
    end
    value = value.(parts{i});
end
end
