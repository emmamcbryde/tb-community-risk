function econConfig = ui_state_to_economics_config_v9(uiState, baseConfig)
%UI_STATE_TO_ECONOMICS_CONFIG_V9 Convert flat UI state to economics config.

if nargin < 2 || isempty(baseConfig)
    baseConfig = build_default_economics_config_v9();
end

econConfig = baseConfig;
if ~isstruct(uiState) || ~isfield(uiState, 'fieldValues') || ~isstruct(uiState.fieldValues)
    return;
end

fields = economics_ui_field_map_v9();
for i = 1:numel(fields)
    componentName = fields(i).componentName;
    if isfield(uiState.fieldValues, componentName)
        econConfig = set_nested_field(econConfig, fields(i).configPath, ...
            normalize_ui_value(uiState.fieldValues.(componentName)));
    end
end
end

