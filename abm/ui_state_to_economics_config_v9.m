end

function s = set_nested_field(s, path, value)
parts = strsplit(path, '.');
if numel(parts) == 1
    s.(parts{1}) = value;
    return;
end

head = parts{1};
tail = strjoin(parts(2:end), '.');
if ~isfield(s, head) || ~isstruct(s.(head))
    s.(head) = struct();
end
s.(head) = set_nested_field(s.(head), tail, value);
end

function value = normalize_ui_value(value)
if iscell(value)
    value = string(value);
end
if isstring(value)
    if isempty(value)
        value = '';
    elseif isscalar(value)
        value = char(value);
    else
        value = char(strjoin(value(:), newline));
    end
end
end
